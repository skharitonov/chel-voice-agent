"""Простановка ударений в тексте перед TTS (опционально, CHEL_STRESS=on).

В API Inworld нет SSML/фонем — ударение определяет сама модель. Единственный рычаг
— знак ударения U+0301 над ударной гласной во входном тексте (подста́нция). Многие
русские TTS его уважают; уважает ли Inworld — проверяется НА СЛУХ. Поэтому фича
по умолчанию ВЫКЛЮЧЕНА.

Применяется только к тексту, идущему в TTS (не к транскрипту/результату). Словарь
ниже — доменные слова, где синтез чаще ошибается; дополняй по мере тестов.
"""

from __future__ import annotations

import re

ACUTE = "́"  # комбинируемый знак ударения (ставится ПОСЛЕ ударной гласной)


def _a(word: str, vowel_index: int) -> str:
    """Вставить знак ударения после гласной с индексом vowel_index (0-based по гласным)."""
    vowels = "аеёиоуыэюяАЕЁИОУЫЭЮЯ"
    seen = -1
    for i, ch in enumerate(word):
        if ch in vowels:
            seen += 1
            if seen == vowel_index:
                return word[: i + 1] + ACUTE + word[i + 1:]
    return word


# Базовые формы -> ударная гласная (индекс по счёту гласных в слове, с 0).
# Пример: «подстанция» гласные о(0) а(1) и(2) я(3) -> ударение на а -> индекс 1.
_BASE = {
    "подстанция": 1, "подстанции": 1, "подстанцию": 1, "подстанций": 1,
    "подстанциями": 1, "подстанциях": 1, "подстанциям": 1,
    "энергетик": 2, "энергетика": 2, "энергетику": 2, "энергетиком": 2,
    "энергетике": 2, "энергетики": 2, "энергетиков": 2,
    "промбезопасности": 3, "промбезопасность": 3,
    "челябинский": 1, "челябинского": 1,
    "экспертиза": 2, "экспертизы": 2, "экспертизу": 2,
    "оборудования": 3, "оборудование": 3, "электрооборудования": 5,
}

# Готовый словарь {слово_в_нижнем_регистре: слово_с_ударением}.
STRESS_MAP = {w: _a(w, idx) for w, idx in _BASE.items()}

_PATTERN = re.compile(r"\b(" + "|".join(sorted(STRESS_MAP, key=len, reverse=True)) + r")\b",
                      re.IGNORECASE)


def apply(text: str) -> str:
    """Расставить ударения по словарю. Сохраняет регистр первой буквы."""
    def repl(m: re.Match) -> str:
        orig = m.group(0)
        accented = STRESS_MAP[orig.lower()]
        if orig[:1].isupper():
            accented = accented[:1].upper() + accented[1:]
        return accented
    return _PATTERN.sub(repl, text)
