def classify(interlocutor_text: str) -> Uks | None:
    """Определить тип возражения секретаря (или None)."""
    t = (interlocutor_text or "").lower()
    for uks in UKS_HANDLERS:
        if any(k in t for k in uks.patterns):
            return uks
        if any(all(sub in t for sub in group) for group in uks.all_groups):
            return uks
    return None


def detect(interlocutor_text: str) -> str | None:
    """Подсказка-директива по возражению (back-compat для pipeline)."""
    uks = classify(interlocutor_text)
    return f"{uks.id}: {uks.hint}" if uks else None


