# Короткие «очеловечивающие» вставки для голоса, когда агента осадили/перебили.
IRRITATION_FILLERS = (
    "А, да, смотрите, если коротко.",
    "Да я буквально на полминуты.",
    "Извините, перебью на секунду.",
    "Понял, по делу.",
)


def detect_irritation(text: str) -> bool:
    """Секретарь говорит резко/раздражённо/на «ты» — нужен живой, не приторный тон."""
    return any(k in (text or "").lower() for k in _IRRITATION)


def pick_filler(text: str) -> str:
    """Подобрать filler детерминированно по реплике (без random — стабильно в тестах)."""
    return IRRITATION_FILLERS[len(text or "") % len(IRRITATION_FILLERS)]


# Нейтральные подтверждающие вставки (foreground-агент): заполняют паузу, пока
# считает медленная модель. Без смысловой нагрузки — поэтому BA их не дублирует.
_ACK_FILLERS = (
    "Так, секунду.",
    "Да, смотрите.",
    "Угу, минуту.",
    "Так, по этому вопросу.",
    "Понял.",
)


def foreground_filler(text: str) -> str:
    """Реплика foreground-агента: при резкости — живая вставка, иначе нейтральное
    подтверждение. Цель — мгновенно (без LLM) заполнить паузу до ответа BA."""
    if detect_irritation(text):
        return pick_filler(text)
    return _ACK_FILLERS[len(text or "") % len(_ACK_FILLERS)]


def underground_answer(text: str) -> str:
    """Ответ на бинарный фильтр УКС-7: underground_yes|underground_no|unknown."""
    low = (text or "").lower()
    if any(k in low for k in _UNDERGROUND_NO):
        return "underground_no"
    if any(k in low for k in _UNDERGROUND_YES):
        return "underground_yes"
    return "unknown"
