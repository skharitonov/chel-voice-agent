_UNDERGROUND_NO = ("нет подземной", "подземной добычи нет", "только поверхность",
                   "открытым способом", "карьер", "нет шахт", "не ведём подземную",
                   "не ведем подземную", "нет подземной добычи")

_UNDERGROUND_YES = ("да, ведётся", "ведём подземную", "ведем подземную", "есть шахта",
                    "подземная есть", "да ведётся", "да, есть", "рудник подземный")


def is_connect_signal(text: str) -> bool:
    """Секретарь соединяет с ЛПР."""
    return any(k in (text or "").lower() for k in _CONNECT)


