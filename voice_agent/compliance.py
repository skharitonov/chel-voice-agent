"""ComplianceGuard — проверка исходящих реплик и распознавание отказа.

Правила: prompts/shared/compliance.md. Здесь — детерминированные проверки
(быстро, без затрат на LLM). Для сценария A v2 добавлены запреты фабрикаций,
исключённых при адаптации книги продаж ККП (spec §2.5): несуществующие
договорённости, выдуманные предписания/проверки, утверждения о чужом парке как
факте. Фактические ссылки на 116-ФЗ / ГОСТ 14695-80 / срок 25 лет — разрешены
(whitelist), чтобы не было ложных блокировок.
"""

from __future__ import annotations

from dataclasses import dataclass

# Прямая ложь о себе/отношениях с компанией или выдача за должностное лицо.
_FORBIDDEN_LIES = (
    "я ваш поставщик", "мы ваш поставщик", "мы уже работаем", "мы с вами работаем",
    "я из вашей головной", "из головного офиса", "служба безопасности",
    "я из налоговой", "я из полиции", "из прокуратуры", "я ваш руководитель",
    "по поручению директора",
)

# Несуществующие договорённости (фабрикация — приёмы книги ККП исключены).
_FORBIDDEN_FABRICATION = (
    # Стем «договаривал» ловит «(мы с вами уже) договаривались/договаривалась» —
    # прош. время = ложь о прошлой договорённости. Будущее «договоримся/
    # договориться» — другой стем, не задевается.
    "договаривал",
    "он ждёт моего звонка",
    "он ждет моего звонка", "он ждёт звонка", "он ждет звонка", "мы уже общались",
    "вы оставляли заявку", "вы оставляли заказ", "договорились о звонке",
    "вы просили перезвонить",
)

# Выдуманные предписания/проверки (мы не знаем реального статуса ОПО клиента).
_FORBIDDEN_AUTHORITY = (
    "у вас предписание", "придёт проверка", "придет проверка", "к вам придёт проверка",
    "к вам придет проверка", "ростехнадзор вас оштрафу", "вас оштрафуют",
    "выпишут штраф", "эксплуатация ваших подстанций незаконна",
)

# Утверждения о состоянии ЧУЖОГО парка как факте — допустимы ТОЛЬКО условно.
_PARK_CLAIM = (
    "ваши подстанции просрочен", "подстанции просрочены", "ваше оборудование просрочено",
    "у вас оборудование за сроком", "ваши подстанции за сроком",
    "у вас просроченные подстанции", "ваши подстанции отработали срок",
)
_CONDITIONAL = ("если", "может быть", "возможно", "обычно", "как правило",
                "скорее всего", "наверн", "вероятно", "часто")

# Фразы собеседника, означающие отказ -> завершить разговор.
_REFUSAL = (
    "не звоните больше", "не звоните нам", "удалите наш номер", "удалите номер",
    "не интересно, до свидания", "я кладу трубку", "кладу трубку", "не беспокойте",
    "внесу в спам", "отстаньте",
)


@dataclass
class GuardResult:
    ok: bool
    reason: str = ""


def check_agent_reply(reply: str) -> GuardResult:
    """Проверить исходящую реплику агента до озвучивания."""
    low = (reply or "").lower()

    for bad in _FORBIDDEN_LIES:
        if bad in low:
            return GuardResult(False, f"Прямая ложь/подмена лица: '{bad}'")
    for bad in _FORBIDDEN_FABRICATION:
        if bad in low:
            return GuardResult(False, f"Фабрикация договорённости: '{bad}'")
    for bad in _FORBIDDEN_AUTHORITY:
        if bad in low:
            return GuardResult(False, f"Выдуманное предписание/проверка: '{bad}'")
    for claim in _PARK_CLAIM:
        if claim in low and not any(c in low for c in _CONDITIONAL):
            return GuardResult(
                False, f"Утверждение о чужом парке как факте (нужно условно): '{claim}'")
    return GuardResult(True)


def detect_refusal(interlocutor_text: str) -> bool:
    """Обнаружить отказ собеседника в его реплике."""
    low = (interlocutor_text or "").lower()
    return any(r in low for r in _REFUSAL)


